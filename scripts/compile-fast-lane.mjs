#!/usr/bin/env node
/**
 * Compiles contracts/AgentFastLane.sol with the pinned solc-js and writes the
 * ABI + creation bytecode into src/lib/abi/agentFastLane.generated.ts, so the
 * server ships the artifact without a Solidity toolchain at runtime.
 *
 *   node scripts/compile-fast-lane.mjs            # write
 *   node scripts/compile-fast-lane.mjs --check    # fail when the file is stale
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(root, "contracts/AgentFastLane.sol");
const OUT = resolve(root, "src/lib/abi/agentFastLane.generated.ts");
const EVM_VERSION = "paris"; // no PUSH0 / transient storage: runs on every BSC node

const source = readFileSync(SOURCE, "utf8");
const input = {
  language: "Solidity",
  sources: { "AgentFastLane.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: EVM_VERSION,
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
for (const e of output.errors ?? []) process.stderr.write(e.formattedMessage + "\n");
if (errors.length) process.exit(1);

const contracts = output.contracts["AgentFastLane.sol"];
const lane = contracts.AgentFastLane;
const admin = contracts.AgentFastLaneAdmin;
const sourceHash = createHash("sha256").update(source).digest("hex");

const body = `/* eslint-disable */
/**
 * GENERATED by scripts/compile-fast-lane.mjs — do not edit.
 * Source: contracts/AgentFastLane.sol (sha256 ${sourceHash})
 * solc ${solc.version()} · optimizer 200 runs · evmVersion ${EVM_VERSION}
 *
 * TESTNET ONLY. UNAUDITED.
 */
export const AGENT_FAST_LANE_SOLC = ${JSON.stringify(solc.version())};
export const AGENT_FAST_LANE_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};
export const AGENT_FAST_LANE_ABI = ${JSON.stringify(lane.abi)} as const;
export const AGENT_FAST_LANE_BYTECODE = ${JSON.stringify("0x" + lane.evm.bytecode.object)};
export const AGENT_FAST_LANE_DEPLOYED_BYTECODE = ${JSON.stringify("0x" + lane.evm.deployedBytecode.object)};
export const AGENT_FAST_LANE_ADMIN_ABI = ${JSON.stringify(admin.abi)} as const;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    process.stderr.write(`${OUT} is stale — run: node scripts/compile-fast-lane.mjs\n`);
    process.exit(1);
  }
  process.stdout.write("agentFastLane.generated.ts is up to date\n");
} else {
  writeFileSync(OUT, body);
  process.stdout.write(
    `wrote ${OUT}: creation ${lane.evm.bytecode.object.length / 2} B, runtime ${lane.evm.deployedBytecode.object.length / 2} B\n`,
  );
}
